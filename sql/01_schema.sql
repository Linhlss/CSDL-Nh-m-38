-- BTL CSDL Đề tài 17: LƯỢC ĐỒ THAM KHẢO v0 (để nhóm review trước khi khóa v1)
-- PostgreSQL >= 15, dùng trong DB mới: csdl17_cu_tru_demo
-- Dữ liệu 100% mô phỏng; không chứa dữ liệu cá nhân thật.
-- Chưa bao gồm quy tắc nghiệp vụ xuyên bảng, xem 02_constraints.sql.

CREATE TABLE IF NOT EXISTS to_dan_pho (
    ma_to          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten_to         VARCHAR(60) NOT NULL UNIQUE,
    ghi_chu        TEXT
);

CREATE TABLE IF NOT EXISTS dia_chi (
    ma_dia_chi     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_to          BIGINT NOT NULL REFERENCES to_dan_pho(ma_to),
    dia_chi_chuan  VARCHAR(200) NOT NULL,
    ghi_chu        TEXT,
    CONSTRAINT uq_dia_chi_to UNIQUE (ma_to, dia_chi_chuan)
);

CREATE TABLE IF NOT EXISTS ho_cu_tru (
    ma_ho          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_dia_chi     BIGINT NOT NULL REFERENCES dia_chi(ma_dia_chi),
    ngay_lap       DATE NOT NULL,
    ghi_chu        TEXT
);

CREATE TABLE IF NOT EXISTS cu_dan (
    ma_cu_dan      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ho_ten         VARCHAR(120) NOT NULL,
    ngay_sinh      DATE NOT NULL,
    gioi_tinh      VARCHAR(10) NOT NULL,
    ghi_chu        TEXT,
    CONSTRAINT ck_cu_dan_gioi_tinh CHECK (gioi_tinh IN ('Nam', 'Nu', 'Khac'))
);

CREATE TABLE IF NOT EXISTS qua_trinh_cu_tru (
    ma_qua_trinh   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_cu_dan      BIGINT NOT NULL REFERENCES cu_dan(ma_cu_dan),
    ma_ho          BIGINT NOT NULL REFERENCES ho_cu_tru(ma_ho),
    loai_cu_tru    VARCHAR(20) NOT NULL,
    ngay_bat_dau   DATE NOT NULL,
    ngay_ket_thuc  DATE,
    CONSTRAINT ck_qt_loai CHECK (loai_cu_tru IN ('THUONG_TRU', 'TAM_TRU')),
    CONSTRAINT ck_qt_ngay CHECK (ngay_ket_thuc IS NULL OR ngay_ket_thuc >= ngay_bat_dau)
);

CREATE TABLE IF NOT EXISTS tai_khoan (
    ma_tai_khoan   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten_dang_nhap  VARCHAR(60) NOT NULL UNIQUE,
    ten_hien_thi   VARCHAR(120) NOT NULL,
    vai_tro        VARCHAR(20) NOT NULL,
    trang_thai     VARCHAR(20) NOT NULL DEFAULT 'HOAT_DONG',
    CONSTRAINT ck_tk_vai_tro CHECK (vai_tro IN ('QUAN_TRI', 'CAN_BO', 'THONG_KE')),
    CONSTRAINT ck_tk_trang_thai CHECK (trang_thai IN ('HOAT_DONG', 'KHOA'))
);

CREATE TABLE IF NOT EXISTS bien_dong_cu_tru (
    ma_bien_dong       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loai_bien_dong     VARCHAR(20) NOT NULL,
    ma_qua_trinh_cu    BIGINT REFERENCES qua_trinh_cu_tru(ma_qua_trinh),
    ma_qua_trinh_moi   BIGINT REFERENCES qua_trinh_cu_tru(ma_qua_trinh),
    ngay_bien_dong     DATE NOT NULL,
    ma_tai_khoan       BIGINT NOT NULL REFERENCES tai_khoan(ma_tai_khoan),
    thoi_diem_ghi      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ghi_chu            TEXT,
    CONSTRAINT ck_bd_hinh_dang CHECK (
        (loai_bien_dong = 'CHUYEN_DEN'
         AND ma_qua_trinh_cu IS NULL AND ma_qua_trinh_moi IS NOT NULL)
     OR (loai_bien_dong = 'CHUYEN_DI'
         AND ma_qua_trinh_cu IS NOT NULL AND ma_qua_trinh_moi IS NULL)
     OR (loai_bien_dong = 'CHUYEN_NOI_BO'
         AND ma_qua_trinh_cu IS NOT NULL AND ma_qua_trinh_moi IS NOT NULL
         AND ma_qua_trinh_cu <> ma_qua_trinh_moi)
    )
);

-- Thêm chỉ mục theo nhu cầu truy vấn sau khi có dữ liệu.
CREATE INDEX IF NOT EXISTS idx_dia_chi_to ON dia_chi(ma_to);
CREATE INDEX IF NOT EXISTS idx_ho_dia_chi ON ho_cu_tru(ma_dia_chi);
CREATE INDEX IF NOT EXISTS idx_qt_cu_dan_ngay ON qua_trinh_cu_tru(ma_cu_dan, ngay_bat_dau);
CREATE INDEX IF NOT EXISTS idx_qt_ho_ngay ON qua_trinh_cu_tru(ma_ho, ngay_bat_dau);
CREATE INDEX IF NOT EXISTS idx_bd_loai_ngay ON bien_dong_cu_tru(loai_bien_dong, ngay_bien_dong);

